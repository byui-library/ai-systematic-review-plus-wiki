import yaml

from review import tables, wiki
from review.config import load_project
from review.papers import included_papers

DOE, KIM = 'doi:10.1000/example.001', 'doi:10.1000/example.005'


def _with_columns(paths, appraisal='AXIS'):
    data = yaml.safe_load(paths.project_yaml.read_text(encoding='utf-8'))
    data['extraction_columns'] = [{'name': 'Sample', 'hint': 'n'}, {'name': 'Method', 'hint': 'PCA, FA'}]
    data['appraisal'] = {'tool': appraisal}
    paths.project_yaml.write_text(yaml.safe_dump(data), encoding='utf-8')
    project = load_project(paths.root)
    wiki.scaffold(paths, project)
    return project, {p.id: p for p in included_papers(paths, project)}


def _set(paths, paper, **meta_changes):
    page = paths.wiki / paper.page_rel
    meta, body = wiki.read_page(page)
    for key, value in meta_changes.items():
        meta[key] = {**meta[key], **value} if isinstance(value, dict) and isinstance(meta.get(key), dict) else value
    wiki.write_page(page, meta, body)


def test_extraction_tables_per_tier(classified):
    paths, _ = classified
    project, papers = _with_columns(paths)
    _set(paths, papers[DOE], status='confirmed', extraction={'Sample': 'n=40 | collegiate', 'Method': 'PCA'})
    written = tables.build_tables(paths, project)
    text = (paths.wiki / 'tables/tier1-extraction.md').read_text(encoding='utf-8')
    assert '| # | Study (Year) | Sample | Method |' in text
    assert '[[papers/tier1/01-doe-2021\\|Doe 2021]]' in text and 'n=40 \\| collegiate' in text and '| PCA |' in text
    assert text.startswith('# Tier 1 extraction: Core Match') and 'Generated by' in text
    tier2 = (paths.wiki / 'tables/tier2-extraction.md').read_text(encoding='utf-8')
    assert '| … | … |' in tier2                                   # still a stub
    assert paths.wiki / 'tables/appraisal.md' in written


def test_appraisal_table_and_legend(classified):
    paths, _ = classified
    project, papers = _with_columns(paths)
    _set(paths, papers[DOE], status='confirmed', appraisal={'items': {f'q{i}': 'yes' for i in range(1, 21)},
                                                             'overall': 'high'})
    tables.build_tables(paths, project)
    text = (paths.wiki / 'tables/appraisal.md').read_text(encoding='utf-8')
    assert '| # | Study (Year) | q1 |' in text and '| Overall |' in text and '| high |' in text
    assert 'q19' in text and 'Were the aims or objectives of the study clear?' in text


def test_no_appraisal_tool_removes_the_table(classified):
    paths, _ = classified
    project, _ = _with_columns(paths)
    tables.build_tables(paths, project)
    project, _ = _with_columns(paths, appraisal='none')
    tables.build_tables(paths, project)
    assert not (paths.wiki / 'tables/appraisal.md').exists()
