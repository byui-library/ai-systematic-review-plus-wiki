"""Frequency figures for the wiki: papers per tier, year, and source, and the commonest extraction values."""
from __future__ import annotations

import re
import shutil
from collections import Counter
from pathlib import Path

from .config import Paths, Project
from .papers import included_papers
from .wiki import read_page, write_text

BANNER = '> Generated by `py run.py figures` from the paper pages. Do not edit; it is rebuilt.\n'


def count_values(values) -> Counter:
    """Split on ';', ignore case and whitespace, and skip blanks and NR (not reported)."""
    counts: Counter = Counter()
    for value in values:
        for part in str(value or '').split(';'):
            term = ' '.join(part.split()).lower()
            if term and term != 'nr':
                counts[term] += 1
    return counts


def _bar(counts: Counter, title: str, path: Path, top: int | None = None, sort_keys: bool = False) -> Path:
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    items = sorted(counts.items()) if sort_keys else counts.most_common(top)
    labels, values = [str(k) for k, _ in items], [v for _, v in items]
    fig, ax = plt.subplots(figsize=(8, max(2.5, 0.4 * len(items) + 1)))
    ax.barh(labels[::-1], values[::-1], color='#1F4E79')
    ax.set_title(title)
    ax.set_xlabel('Papers')
    ax.xaxis.get_major_locator().set_params(integer=True)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return path


def build_figures(paths: Paths, project: Project) -> list[Path]:
    papers = included_papers(paths, project)
    out_dir = paths.wiki / 'figures'
    metas = []
    for p in papers:
        page = paths.wiki / p.page_rel
        meta = read_page(page)[0] if page.exists() else {}
        if meta.get('status', 'stub') != 'stub':
            metas.append(meta)

    charts: list[tuple[str, Path]] = []
    labels = {t.id: f'Tier {t.id}: {t.label}' for t in project.tiers}
    charts.append(('Papers per tier', _bar(Counter(labels[p.tier] for p in papers), 'Papers per tier',
                                           out_dir / 'papers-per-tier.png', sort_keys=True)))
    charts.append(('Papers per year', _bar(Counter(p.year for p in papers), 'Papers per year',
                                           out_dir / 'papers-per-year.png', sort_keys=True)))
    sources = Counter(s for p in papers for s in (p.get('sources', []) or []))
    charts.append(('Papers per database', _bar(sources, 'Papers per database', out_dir / 'papers-per-source.png')))
    for column in project.extraction_columns:
        counts = count_values((m.get('extraction') or {}).get(column['name']) for m in metas)
        slug = re.sub(r'[^a-z0-9]+', '-', column['name'].lower()).strip('-')
        target = out_dir / f'top-{slug}.png'
        if counts:
            charts.append((f'Most common: {column["name"]}', _bar(counts, column['name'], target, top=10)))
        else:
            target.unlink(missing_ok=True)

    prisma = out_dir / 'prisma.png'
    if paths.prisma_png.exists():
        shutil.copy(paths.prisma_png, prisma)
        charts.insert(0, ('PRISMA flow', prisma))
    else:
        prisma.unlink(missing_ok=True)

    page = ['# Figures', '', BANNER]
    for title, path in charts:
        page += [f'## {title}', '', f'![{title}](../figures/{path.name})', '']
    write_text(paths.wiki / 'tables/figures.md', '\n'.join(page))
    return [path for _, path in charts]
