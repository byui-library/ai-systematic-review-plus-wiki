"""An interactive knowledge graph of the wiki, built from its [[wikilinks]]."""
from __future__ import annotations

import json
import re
from collections import Counter, defaultdict
from pathlib import Path

from .config import Paths
from .vault_text import markdown_table
from .wiki import page_title, write_text

VIS_NETWORK = 'https://unpkg.com/vis-network@9.1.9/standalone/umd/vis-network.min.js'
COMMENT = re.compile(r'<!--.*?-->', re.S)   # placeholder text in stubs, not real links
LINK = re.compile(r'\[\[([^\]|\\]+?)(?:\\?\|[^\]]*)?\]\]')
SKIP = {'index', 'log', 'AGENTS', 'CLAUDE'}
COLOURS = {'papers': '#1F4E79', 'concepts': '#2E7D32', 'debates': '#C62828', 'sub-reviews': '#6A1B9A',
           'methods-review': '#757575', 'home': '#757575'}


def parse_links(text: str) -> list[str]:
    targets = []
    for m in LINK.finditer(COMMENT.sub('', text)):
        target = m.group(1).strip()
        targets.append(target[:-3] if target.endswith('.md') else target)
    return targets


def _node_ids(wiki_dir: Path) -> dict[str, Path]:
    nodes = {}
    for path in wiki_dir.rglob('*.md'):
        rel = path.relative_to(wiki_dir).with_suffix('').as_posix()
        top = rel.split('/')[0]
        if top in ('raw', 'tables') or rel in SKIP or re.fullmatch(r'concepts/[^/]+/index', rel):
            continue
        nodes[rel] = path
    return nodes


def build_graph(paths: Paths) -> dict:
    wiki_dir = paths.wiki
    nodes = _node_ids(wiki_dir)
    every_page = {p.relative_to(wiki_dir).with_suffix('').as_posix() for p in wiki_dir.rglob('*.md')}
    by_stem = defaultdict(list)
    for node_id in nodes:
        by_stem[node_id.split('/')[-1]].append(node_id)

    def resolve(target: str) -> str | None:
        if target in nodes:
            return target
        matches = by_stem.get(target.split('/')[-1], [])
        return matches[0] if len(matches) == 1 else None

    edges, unresolved = set(), 0
    for source, path in nodes.items():
        for target in parse_links(path.read_text(encoding='utf-8')):
            resolved = resolve(target)
            if resolved is None:
                unresolved += target not in every_page   # links to index, log, or tables exist but are not drawn
            elif resolved != source:
                edges.add((source, resolved))
    degree = Counter()
    for a, b in edges:
        degree[a] += 1
        degree[b] += 1
    titles = {node_id: page_title(path) for node_id, path in nodes.items()}

    data = {
        'nodes': [{'id': n, 'label': titles[n][:40], 'title': titles[n],
                   'group': n.split('/')[0] if '/' in n else 'home', 'value': 1 + degree[n],
                   'url': f'../{n}.html', 'color': COLOURS.get(n.split('/')[0], '#757575')}
                  for n in sorted(nodes)],
        'edges': [{'from': a, 'to': b} for a, b in sorted(edges)],
    }
    html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Knowledge graph</title>
<script src="{VIS_NETWORK}"></script>
<style>
  body {{ margin: 0; font-family: system-ui, sans-serif; background: #fff; color: #222; }}
  #graph {{ width: 100vw; height: 100vh; }}
  #legend {{ position: fixed; top: 8px; left: 8px; background: #ffffffdd; padding: 6px 10px; border-radius: 6px; font-size: 13px; }}
</style>
</head>
<body>
<div id="legend">Node size = number of links. Drag to explore; double-click a node to open its page.</div>
<div id="graph"></div>
<script>
const GRAPH = {json.dumps(data, ensure_ascii=False)};
const network = new vis.Network(document.getElementById('graph'),
  {{ nodes: new vis.DataSet(GRAPH.nodes), edges: new vis.DataSet(GRAPH.edges) }},
  {{ nodes: {{ shape: 'dot', scaling: {{ min: 6, max: 30 }}, font: {{ size: 12 }} }},
     edges: {{ color: '#bbbbbb', smooth: false }}, physics: {{ stabilization: true }} }});
network.on('doubleClick', p => {{ if (p.nodes.length) window.location.href = GRAPH.nodes.find(n => n.id === p.nodes[0]).url; }});
</script>
</body>
</html>
"""
    write_text(wiki_dir / 'tables/knowledge-graph.html', html)
    top = [[f'[[{n}|{titles[n]}]]', degree[n]] for n, _ in degree.most_common(10)]
    summary = ['# Knowledge graph', '',
               '> Generated by `py run.py graph` from the links between wiki pages. Do not edit; it is rebuilt.', '',
               '[Open the interactive graph](knowledge-graph.html)', '',
               f'{len(nodes)} pages, {len(edges)} links between them; {unresolved} link(s) could not be resolved '
               '(the target page is missing, or its name matches more than one page).', '',
               '## Most-connected pages', '', markdown_table(['Page', 'Links'], top) if top else '_No links yet._']
    write_text(wiki_dir / 'tables/knowledge-graph.md', '\n'.join(summary) + '\n')
    return {'nodes': len(nodes), 'edges': len(edges), 'unresolved': unresolved}
