"""Extraction and appraisal tables, built only from paper pages' front-matter."""
from __future__ import annotations

from pathlib import Path

from .appraisal import checklist
from .config import Paths, Project
from .papers import Paper, included_papers, surname
from .vault_text import markdown_table
from .wiki import read_page, write_text

BANNER = "> Generated by `py run.py wiki --tables` from the paper pages' front-matter. Do not edit; it is rebuilt.\n"
PENDING = '…'


def _study(paper: Paper) -> str:
    name = surname(paper.get('authors')).replace('-', ' ').title()
    return f'[[{paper.page_rel[:-3]}|{name} {paper.year}]]'   # markdown_table escapes the pipe for tables


def _meta(paths: Paths, paper: Paper) -> dict:
    page = paths.wiki / paper.page_rel
    return read_page(page)[0] if page.exists() else {}


def build_tables(paths: Paths, project: Project) -> list[Path]:
    papers = included_papers(paths, project)
    metas = {p.id: _meta(paths, p) for p in papers}
    columns = [c['name'] for c in project.extraction_columns]
    written = []
    for tier in [t for t in project.tiers if t.included]:
        rows = []
        for p in (p for p in papers if p.tier == tier.id):
            meta = metas[p.id]
            extraction = meta.get('extraction') or {}
            pending = meta.get('status', 'stub') == 'stub'
            rows.append([p.number, _study(p)] + [PENDING if pending else extraction.get(c, '') for c in columns])
        path = paths.wiki / f'tables/tier{tier.id}-extraction.md'
        write_text(path, f'# Tier {tier.id} extraction: {tier.label}\n\n{BANNER}\n'
                         + markdown_table(['#', 'Study (Year)'] + columns, rows))
        written.append(path)

    appraisal_path = paths.wiki / 'tables/appraisal.md'
    tool = checklist(project.appraisal_tool)
    if not tool:
        appraisal_path.unlink(missing_ok=True)
        return written
    keys = [key for key, _ in tool['items']]
    rows = []
    for p in papers:
        appraisal = metas[p.id].get('appraisal') or {}
        items = appraisal.get('items') or {}
        rows.append([p.number, _study(p)] + [items.get(k) or PENDING for k in keys] + [appraisal.get('overall') or PENDING])
    legend = markdown_table(['Key', 'Question'], [list(item) for item in tool['items']])
    write_text(appraisal_path, f'# Quality appraisal: {project.appraisal_tool}\n\n{BANNER}\n'
                               + markdown_table(['#', 'Study (Year)'] + keys + ['Overall'], rows)
                               + f"\n## Legend\n\n{tool['name']}. Answers: {', '.join(tool['answers'])}. "
                               + f"{tool['note']}\n\n{legend}")
    written.append(appraisal_path)
    return written
