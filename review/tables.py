"""Extraction and appraisal tables, built only from paper pages' front-matter, plus a spreadsheet export."""
from __future__ import annotations

import csv
from pathlib import Path

from openpyxl import Workbook

from .appraisal import checklist
from .config import Paths, Project
from .errors import PipelineError
from .excel import csv_safe, save_workbook, sheet_name, write_table
from .papers import Paper, included_papers, surname
from .vault_text import markdown_table
from .wiki import as_answer, read_meta, write_text

BANNER = "> Generated by `py run.py wiki --tables` from the paper pages' front-matter. Do not edit; it is rebuilt.\n"
PENDING = '…'


def _name(paper: Paper) -> str:
    return f"{surname(paper.get('authors')).replace('-', ' ').title()} {paper.year}"


def _study(paper: Paper) -> str:
    return f'[[{paper.page_rel[:-3]}|{_name(paper)}]]'   # markdown_table escapes the pipe for tables


def _meta(paths: Paths, paper: Paper) -> dict:
    return read_meta(paths.wiki / paper.page_rel) or {}   # a page with broken front-matter shows as pending


def _status(meta: dict) -> str:
    """One rule for every output: a page with no status yet is still a stub."""
    return meta.get('status') or 'stub'


def export_extraction(paths: Paths, project: Project, papers: list[Paper], metas: dict) -> list[Path]:
    """data/extraction.xlsx (All + one sheet per included tier) and data/extraction.csv, for analysis."""
    columns = [c['name'] for c in project.extraction_columns]
    keys = ['tier', 'number', 'study', 'title', 'year', 'doi', 'status'] + [f'x:{c}' for c in columns] + ['overall']
    titles = ['Tier', '#', 'Study', 'Title', 'Year', 'DOI', 'Status'] + columns + ['Appraisal overall']
    rows = []
    for p in papers:
        meta = metas[p.id]
        status = _status(meta)
        written = status != 'stub'
        extraction = (meta.get('extraction') or {}) if written else {}
        row = {'tier': p.tier, 'number': p.number, 'study': _name(p), 'title': p.get('title'), 'year': p.year,
               'doi': p.get('doi'), 'status': status,
               'overall': as_answer((meta.get('appraisal') or {}).get('overall')) if written else None}
        row.update({f'x:{c}': as_answer(extraction.get(c)) for c in columns})
        rows.append(row)
    spec = list(zip(keys, titles, [6, 5, 22, 50, 6, 26, 10] + [24] * len(columns) + [12]))
    wb = Workbook()
    write_table(wb.active, spec, rows)
    wb.active.title = 'All'
    for tier in (t for t in project.tiers if t.included):
        write_table(wb.create_sheet(sheet_name(f'T{tier.id} {tier.label}')), spec,
                    [r for r in rows if r['tier'] == tier.id])
    save_workbook(wb, paths.extraction_xlsx)
    try:
        with open(paths.extraction_csv, 'w', encoding='utf-8-sig', newline='') as f:
            writer = csv.writer(f)
            writer.writerow(titles)
            writer.writerows([csv_safe(r[k]) for k in keys] for r in rows)
    except PermissionError as exc:
        raise PipelineError(f'Could not write {paths.extraction_csv.name}. If it is open in Excel, close it and '
                            'run again.') from exc
    return [paths.extraction_xlsx, paths.extraction_csv]


def build_tables(paths: Paths, project: Project) -> list[Path]:
    papers = included_papers(paths, project)
    metas = {p.id: _meta(paths, p) for p in papers}
    columns = [c['name'] for c in project.extraction_columns]
    written = []
    for tier in [t for t in project.tiers if t.included]:
        rows = []
        for p in (p for p in papers if p.tier == tier.id):
            meta = metas[p.id]
            extraction = meta.get('extraction') or {}
            pending = _status(meta) == 'stub'
            rows.append([p.number, _study(p)] + [PENDING if pending else as_answer(extraction.get(c, '')) for c in columns])
        path = paths.wiki / f'tables/tier{tier.id}-extraction.md'
        write_text(path, f'# Tier {tier.id} extraction: {tier.label}\n\n{BANNER}\n'
                         + markdown_table(['#', 'Study (Year)'] + columns, rows))
        written.append(path)

    appraisal_path = paths.wiki / 'tables/appraisal.md'
    tool = checklist(project.appraisal_tool)
    if tool:
        keys = [key for key, _ in tool['items']]
        rows = []
        for p in papers:
            appraisal = metas[p.id].get('appraisal') or {}
            items = appraisal.get('items') or {}
            rows.append([p.number, _study(p)] + [as_answer(items.get(k)) or PENDING for k in keys]
                        + [as_answer(appraisal.get('overall')) or PENDING])
        legend = markdown_table(['Key', 'Question'], [list(item) for item in tool['items']])
        write_text(appraisal_path, f'# Quality appraisal: {project.appraisal_tool}\n\n{BANNER}\n'
                                   + markdown_table(['#', 'Study (Year)'] + keys + ['Overall'], rows)
                                   + f"\n## Legend\n\n{tool['name']}. Answers: {', '.join(tool['answers'])}. "
                                   + f"{tool['note']}\n\n{legend}")
        written.append(appraisal_path)
    else:
        appraisal_path.unlink(missing_ok=True)
    # The spreadsheet comes last: a copy left open in Excel must not stop the wiki tables being rebuilt.
    return written + export_extraction(paths, project, papers, metas)
