"""Build the wiki into a website with MkDocs Material.

Targets: local (with PDFs, for your own computer), github_pages (public, never any PDFs), and
openequella (BYU-I sign-in, with PDFs). mkdocs.yml is generated on every build; do not edit it.
"""
from __future__ import annotations

import logging
import os
from contextlib import contextmanager
from pathlib import Path

import yaml

from . import state
from .config import Paths, Project
from .errors import PipelineError

TARGETS = ('local', 'github_pages', 'openequella')
HOOK = Path(__file__).resolve().parent / 'mkdocs_hooks.py'
ALWAYS_EXCLUDED = ['AGENTS.md', 'CLAUDE.md', 'raw/inbox/', '.obsidian/', '*.part', '*.tmp']


def site_dir(paths: Paths, target: str) -> Path:
    return paths.root / ('site' if target == 'local' else f'site-{target}')


def write_mkdocs_config(paths: Paths, project: Project, target: str) -> Path:
    if target not in TARGETS:
        raise PipelineError(f"Unknown site target '{target}'. Choose one of: {', '.join(TARGETS)}")
    if not (paths.wiki / 'index.md').exists():
        raise PipelineError('There is no wiki to publish yet. Run: py run.py wiki --scaffold')
    excluded = ALWAYS_EXCLUDED + (['raw/'] if target == 'github_pages' else [])
    config = {
        'site_name': project.raw['site'].get('title') or project.title,
        'site_description': project.question,
        'docs_dir': 'wiki',
        'site_dir': site_dir(paths, target).name,
        'use_directory_urls': False,   # page.html URLs keep relative PDF and graph links working
        'theme': {'name': 'material',
                  'features': ['navigation.tabs', 'navigation.sections', 'navigation.top',
                               'search.highlight', 'search.suggest', 'content.tables'],
                  'palette': [{'scheme': 'default', 'primary': 'indigo', 'accent': 'indigo'}]},
        'markdown_extensions': ['tables', 'admonition', {'toc': {'permalink': True}}],
        'hooks': [HOOK.as_posix()],   # absolute: the project folder (e.g. demo-workspace) may not contain review/
        'exclude_docs': '\n'.join(excluded) + '\n',
    }
    path = paths.root / 'mkdocs.yml'
    path.write_text('# Generated by `py run.py site` on every build. Do not edit; change project.yaml instead.\n'
                    + yaml.safe_dump(config, sort_keys=False, allow_unicode=True), encoding='utf-8')
    return path


@contextmanager
def _pdfs_excluded(exclude: bool):
    previous = os.environ.get('REVIEW_EXCLUDE_PDFS')
    os.environ['REVIEW_EXCLUDE_PDFS'] = '1' if exclude else '0'
    try:
        yield
    finally:
        if previous is None:
            os.environ.pop('REVIEW_EXCLUDE_PDFS', None)
        else:
            os.environ['REVIEW_EXCLUDE_PDFS'] = previous


class _Warnings(logging.Handler):
    def __init__(self):
        super().__init__(logging.WARNING)
        self.messages: list[str] = []

    def emit(self, record):
        self.messages.append(record.getMessage())


def _mkdocs():
    try:
        from mkdocs.commands.build import build
        from mkdocs.config import load_config
    except ImportError as exc:
        raise PipelineError('MkDocs is not installed. Run the setup script again '
                            '(or: python -m pip install -r setup/requirements.txt).') from exc
    return load_config, build


def build_site(paths: Paths, project: Project, target: str = 'local') -> tuple[Path, list[str]]:
    """Build the site; returns (output folder, MkDocs warnings)."""
    load_config, build = _mkdocs()
    config_file = write_mkdocs_config(paths, project, target)
    warnings = _Warnings()
    logger = logging.getLogger('mkdocs')
    logger.addHandler(warnings)
    try:
        with _pdfs_excluded(target == 'github_pages'):
            build(load_config(config_file=str(config_file)))
    except Exception as exc:   # MkDocs raises its own error types; show them in plain words
        raise PipelineError(f'The website build failed: {exc}', warnings.messages[-10:]) from exc
    finally:
        logger.removeHandler(warnings)
    out = site_dir(paths, target)
    if target == 'github_pages':
        for pdf in out.rglob('*.pdf'):   # belt and braces: a public site must never carry full texts
            pdf.unlink()
    if target == 'local':
        state.mark_done(paths, 'site', target=target)
    return out, warnings.messages


def serve_site(paths: Paths, project: Project, address: str = '127.0.0.1:8000') -> None:
    _mkdocs()
    from mkdocs.commands.serve import serve
    config_file = write_mkdocs_config(paths, project, 'local')
    with _pdfs_excluded(False):
        serve(config_file=str(config_file), dev_addr=address)
